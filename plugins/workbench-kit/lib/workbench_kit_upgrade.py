def _resolve_workspace(value: str | pathlib.Path) -> pathlib.Path:
    try:
        root = pathlib.Path(value).resolve(strict=True)
        node = os.lstat(root)
    except OSError as error:
        raise CliError("workspace-invalid", str(value)) from error
    if not stat.S_ISDIR(node.st_mode) or stat.S_ISLNK(node.st_mode):
        raise CliError("workspace-invalid", str(value))
    return root


def _frontmatter(raw: bytes) -> dict[str, str]:
    try:
        lines = raw.decode("utf-8", errors="strict").splitlines()
    except UnicodeDecodeError as error:
        raise CliError("migration-task-invalid", "task/index.md") from error
    if not lines or lines[0] != "---":
        raise CliError("migration-task-invalid", "task/index.md")
    try:
        end = lines.index("---", 1)
    except ValueError as error:
        raise CliError("migration-task-invalid", "task/index.md") from error
    values = {}
    for line in lines[1:end]:
        if not line or ":" not in line:
            raise CliError("migration-task-invalid", "task/index.md")
        key, value = line.split(":", 1)
        if (
            not key
            or key.strip() != key
            or key in values
            or any(ord(character) < 32 for character in key + value)
        ):
            raise CliError("migration-task-invalid", "task/index.md")
        values[key] = value.strip()
    return values


def read_migration_task(
    workspace: pathlib.Path,
    route: str,
    public_snapshot: dict[str, Any],
    *,
    workspace_home: str | None = None,
) -> dict[str, Any]:
    root = _resolve_workspace(workspace)
    try:
        node = _inspect_node(root, "task/index.md")
    except Exception as error:
        raise CliError("migration-task-invalid", "task/index.md") from error
    if node["node_type"] != "file" or node["mode"] != "100644":
        raise CliError("migration-task-invalid", "task/index.md")
    values = _frontmatter(node["content"])
    if (
        any(
            field not in values
            for field in ("id", "issue", "home", "parent", "branch", "claim_id")
        )
        or any(not values[field] for field in ("id", "issue", "branch", "claim_id"))
    ):
        raise CliError("migration-task-invalid", "task/index.md")
    task_contract = values.get("task_contract") or "workbench-task/v1"
    expected = (
        "workbench-task/v2" if route == "current-v2" else "workbench-task/v1"
    )
    if task_contract != expected:
        raise CliError(
            "migration-task-contract-invalid", "task/index.md"
        )
    try:
        branch_result = subprocess.run(
            ["git", "-C", str(root), "symbolic-ref", "--quiet", "--short", "HEAD"],
            capture_output=True,
            check=False,
        )
        current_branch = branch_result.stdout.decode("utf-8", errors="strict").strip()
    except (OSError, UnicodeDecodeError) as error:
        raise CliError("migration-task-identity-invalid", "HEAD") from error
    if branch_result.returncode != 0 or current_branch != values["branch"]:
        raise CliError("migration-task-identity-invalid", "HEAD")
    if expected == "workbench-task/v1":
        if not isinstance(workspace_home, str) or not workspace_home:
            raise CliError(
                "migration-task-identity-invalid", "workspace_home"
            )
        active = public_snapshot.get("active_v1_tasks")
        if not isinstance(active, list):
            raise CliError("migration-task-identity-invalid", "legacy-inventory")
        matches = [
            claim for claim in active
            if isinstance(claim, dict) and claim.get("branch") == current_branch
        ]
        if len(matches) != 1:
            raise CliError("migration-task-identity-invalid", "legacy-inventory")
        claim = matches[0]
        claim_home = claim.get("home")
        expected_id = f"{claim_home}#{claim.get('issue')}"
        workspace_claim = claim_home == workspace_home
        valid_ids = (
            {expected_id, str(claim.get("issue"))}
            if workspace_claim
            else {expected_id}
        )
        valid_homes = (
            ("", claim_home) if workspace_claim else (claim_home,)
        )
        local_parent = values.get("parent", "")
        public_parent = claim.get("parent")
        identity_matches = (
            claim.get("claim_id") == values["claim_id"]
            and claim.get("task_claim_id") == values["claim_id"]
            and claim.get("task_contract") == expected
            and values["id"] in valid_ids
            and values.get("issue", str(claim.get("issue")))
            == str(claim.get("issue"))
            and values.get("home", claim_home) in valid_homes
            and local_parent
            == ("" if public_parent is None else str(public_parent))
        )
    else:
        claim = public_snapshot.get("migration_task_claim")
        coordination = public_snapshot.get("doctor", {}).get("writer_coordination", {})
        local_home = values.get("home") or None
        local_parent = values.get("parent") or None
        local_issue = values.get("issue")
        descriptor_digest = values.get("workspace_authority_descriptor_digest")
        identity_matches = (
            isinstance(claim, dict)
            and claim.get("task_id") == values["id"]
            and str(claim.get("issue")) == local_issue
            and claim.get("home") == local_home
            and (
                claim.get("parent") is None
                if local_parent is None
                else str(claim.get("parent")) == local_parent
            )
            and claim.get("claim_id") == values["claim_id"]
            and claim.get("task_contract") == expected
            and claim.get("branch") == current_branch
            and claim.get("workspace_authority_descriptor_digest")
            == coordination.get("descriptor_digest")
            and descriptor_digest
            == claim.get("workspace_authority_descriptor_digest")
            and isinstance(claim.get("workspace_authority_descriptor_digest"), str)
        )
    if not identity_matches:
        raise CliError("migration-task-identity-invalid", "task/index.md")
    return {
        "task_id": values["id"],
        "claim_id": values["claim_id"],
        "task_contract": task_contract,
        "branch": values["branch"],
        "index_digest": canonical_digest(node["content"], raw=True),
    }


def _no_symlink_path(path: pathlib.Path) -> pathlib.Path:
    if not path.is_absolute():
        raise CliError("input-file-invalid", str(path))
    current = pathlib.Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        try:
            node = os.lstat(current)
        except OSError as error:
            raise CliError("input-file-invalid", str(path)) from error
        if stat.S_ISLNK(node.st_mode):
            raise CliError("input-file-unsafe", str(path))
        if current != path and not stat.S_ISDIR(node.st_mode):
            raise CliError("input-file-unsafe", str(path))
    return current


def _read_external_file(
    path: pathlib.Path, workspace: pathlib.Path
) -> bytes:
    raw_path = pathlib.Path(path)
    checked = _no_symlink_path(raw_path)
    root = _resolve_workspace(workspace)
    resolved = checked.resolve(strict=True)
    if resolved == root or root in resolved.parents:
        raise CliError("input-file-unsafe", str(path))
    node = os.lstat(resolved)
    if (
        not stat.S_ISREG(node.st_mode)
        or node.st_uid != os.getuid()
        or node.st_nlink != 1
        or stat.S_IMODE(node.st_mode) & 0o022
    ):
        raise CliError("input-file-unsafe", str(path))
    descriptor = os.open(
        resolved, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    )
    try:
        opened = os.fstat(descriptor)
        if (
            not stat.S_ISREG(opened.st_mode)
            or (opened.st_dev, opened.st_ino) != (node.st_dev, node.st_ino)
            or opened.st_uid != node.st_uid
            or opened.st_nlink != node.st_nlink
            or stat.S_IMODE(opened.st_mode) != stat.S_IMODE(node.st_mode)
            or opened.st_size != node.st_size
            or opened.st_size > MAX_EXTERNAL_INPUT_BYTES
        ):
            raise CliError("input-file-unsafe", str(path))
        chunks = []
        total = 0
        while True:
            chunk = os.read(descriptor, 65536)
            if not chunk:
                break
            total += len(chunk)
            if total > MAX_EXTERNAL_INPUT_BYTES:
                raise CliError("input-file-unsafe", str(path))
            chunks.append(chunk)
        verified = os.fstat(descriptor)
        snapshot_fields = (
            "st_dev",
            "st_ino",
            "st_uid",
            "st_mode",
            "st_nlink",
            "st_size",
            "st_mtime_ns",
            "st_ctime_ns",
        )
        if any(
            getattr(verified, field) != getattr(opened, field)
            for field in snapshot_fields
        ):
            raise CliError("input-file-unsafe", str(path))
        payload = b"".join(chunks)
        if len(payload) != opened.st_size:
            raise CliError("input-file-unsafe", str(path))
        return payload
    finally:
        os.close(descriptor)


def load_receipt_projection(
    path: pathlib.Path,
    workspace: pathlib.Path,
    kind: str,
) -> dict[str, Any]:
    raw = _read_external_file(path, workspace)
    try:
        if kind == "bootstrap-authority":
            projection = parse_authority_approval(raw)
        elif kind == "reviewed-overlay":
            projection = parse_reviewed_overlay(raw)
        elif kind == "removal-approval":
            receipt = validate_removal_approval(
                strict_load(raw, str(path))
            )
            projection = {
                "receipt": receipt,
                "object_digest": canonical_digest(receipt),
                "source_digest": canonical_digest(raw, raw=True),
            }
        else:
            raise CliError("input-kind-invalid", kind)
    except ContractError as error:
        raise CliError("input-file-invalid", str(path)) from error
    return {
        field: projection[field]
        for field in ("receipt", "object_digest", "source_digest")
    }


def route_for_diagnosis(
    diagnosis: dict[str, Any], workspace_schema: str
) -> str:
    classification = diagnosis.get("classification")
    blockers = diagnosis.get("blockers")
    if classification in ("generated-minimal", "embedded-legacy"):
        if workspace_schema == "workbench/v1" and not blockers:
            return "implicit-v1"
    if (
        classification == "malformed"
        and workspace_schema == "workbench/v1"
        and blockers
        and all(
            blocker == {
                "code": "generator-composition-invalid",
                "ref": "AGENTS.md",
            }
            for blocker in blockers
        )
    ):
        return "implicit-v1"
    if (
        classification == "migration-staged"
        and workspace_schema == "workbench/v2"
        and not blockers
    ):
        return "staged-v2"
    if (
        classification == "already-current"
        and workspace_schema == "workbench/v2"
        and not blockers
    ):
        return "current-v2"
    raise CliError("classification-not-actionable", str(classification))


def language_decision(tag: str, route: str) -> dict[str, Any]:
    source = "explicit-cli" if route == "implicit-v1" else "workspace-profile"
    source_ref = "argv:--language" if route == "implicit-v1" else ".workbench/profile.conf"
    language = {
        "contract_version": "workbench-kit-language-decision/v1",
        "tag": tag,
        "source": source,
        "source_ref": source_ref,
        "digest": None,
    }
    language["digest"] = canonical_digest(language, null_field="digest")
    try:
        return validate_language(language)
    except ContractError as error:
        raise CliError("language-invalid", tag) from error


def _optional_projection(
    request: dict[str, Any],
    workspace: pathlib.Path,
    field: str,
    kind: str,
) -> dict[str, Any] | None:
    value = request[field]
    if value is None:
        return None
    return load_receipt_projection(pathlib.Path(value), workspace, kind)


def plan_from_snapshot(
    workspace: pathlib.Path,
    *,
    request: dict[str, Any],
    bundle: dict[str, Any],
    public_snapshot: dict[str, Any],
    receipt_inputs: dict[str, dict[str, Any] | None] | None = None,
) -> dict[str, Any]:
    root = _resolve_workspace(workspace)
    if _resolve_workspace(request["workspace"]) != root:
        raise CliError("workspace-mismatch", request["workspace"])
    equivalence_input = bundle.get("plugin_equivalence_input")
    if request["remove_embedded_engine"] and equivalence_input is None:
        raise CliError("plugin-equivalence-unavailable", "embedded-engine")
    diagnosis = diagnose_workspace(
        root,
        public_snapshot,
        generator_receipts=bundle["generator_receipts"],
        equivalence_receipt=(
            equivalence_input["receipt"] if equivalence_input is not None else None
        ),
        legacy_engine_markers=bundle.get("legacy_engine_markers", ()),
    )
    route = route_for_diagnosis(
        diagnosis, public_snapshot["contract"]["workspace"]["schema"]
    )
    validate_route_flags(request, route)
    if receipt_inputs is None:
        authority_input = _optional_projection(
            request,
            root,
            "authority_approval_file",
            "bootstrap-authority",
        )
        reviewed_overlay_input = _optional_projection(
            request,
            root,
            "reviewed_overlay_file",
            "reviewed-overlay",
        )
        removal_approval_input = _optional_projection(
            request,
            root,
            "removal_approval_file",
            "removal-approval",
        )
    else:
        authority_input = receipt_inputs["authority"]
        reviewed_overlay_input = receipt_inputs["reviewed_overlay"]
        removal_approval_input = receipt_inputs["removal_approval"]
    workspace_home = (
        authority_input["receipt"]["proposed_descriptor"]["workspace_home"]
        if authority_input is not None
        else None
    )
    migration_task = read_migration_task(
        root,
        route,
        public_snapshot,
        workspace_home=workspace_home,
    )
    embedded_verified = (
        diagnosis["embedded_engine"]["state"] == "present-verified"
    )
    plan_equivalence = equivalence_input if embedded_verified else None
    engine_manifest_projection = (
        public_snapshot.get("engine_manifest_projection")
        if embedded_verified
        else None
    )
    if embedded_verified and engine_manifest_projection is None:
        raise CliError("plugin-equivalence-unavailable", "engine-manifest")
    try:
        if route == "current-v2":
            return build_current_plan(
                root,
                diagnosis=diagnosis,
                public_snapshot=public_snapshot,
                migration_task=migration_task,
                planner=bundle["planner"],
                engine_manifest_projection=engine_manifest_projection,
                plugin_equivalence_input=plan_equivalence,
                remove_embedded=request["remove_embedded_engine"],
                removal_approval_input=removal_approval_input,
            )
        tag = request["language"] if route == "implicit-v1" else diagnosis["language"]
        language = language_decision(tag, route)
        return build_migration_plan(
            root,
            diagnosis=diagnosis,
            public_snapshot=public_snapshot,
            authority_input=authority_input,
            language=language,
            migration_task=migration_task,
            planner=bundle["planner"],
            generator_receipt=bundle["target_generator_receipt"],
            reviewed_overlay_input=reviewed_overlay_input,
            engine_manifest_projection=engine_manifest_projection,
            plugin_equivalence_input=plan_equivalence,
            remove_embedded=request["remove_embedded_engine"],
            removal_approval_input=removal_approval_input,
        )
    except PlanningError as error:
        raise CliError(error.code, error.ref) from error


def _staged_inventory_mode(root: pathlib.Path) -> str | None:
    try:
        node = _inspect_node(root, ".workbench/migration.json")
        if node["node_type"] != "file" or node["mode"] != "100644":
            return None
        receipt = validate_migration_receipt(
            strict_load(node["content"], ".workbench/migration.json")
        )
        if node["content"] != canonical_bytes(receipt):
            return None
        return "bootstrap-show"
    except (ContractError, OSError):
        return None


def _embedded_candidate_present(
    root: pathlib.Path, equivalence_input: dict[str, Any] | None
) -> bool:
    if equivalence_input is None:
        return False
    receipt = equivalence_input["receipt"]
    for path in receipt["allowed_roots"]:
        if _inspect_node(root, path)["node_type"] != "absent":
            return True
    for link in receipt["discovery_links"]:
        if _inspect_node(root, link["path"])["node_type"] != "absent":
            return True
    return False


def _dry_run_upgrade_locked(
    request: dict[str, Any],
    bundle: dict[str, Any],
    root: pathlib.Path,
    root_fd: int,
) -> dict[str, Any]:
    require_workspace_binding(root_fd, root)
    receipt_inputs = {
        "authority": _optional_projection(
            request,
            root,
            "authority_approval_file",
            "bootstrap-authority",
        ),
        "reviewed_overlay": _optional_projection(
            request,
            root,
            "reviewed_overlay_file",
            "reviewed-overlay",
        ),
        "removal_approval": _optional_projection(
            request,
            root,
            "removal_approval_file",
            "removal-approval",
        ),
    }
    equivalence_input = bundle.get("plugin_equivalence_input")
    if request["remove_embedded_engine"] and equivalence_input is None:
        raise CliError("plugin-equivalence-unavailable", "embedded-engine")
    include_manifest = _embedded_candidate_present(root, equivalence_input)
    authority_path = (
        pathlib.Path(request["authority_approval_file"])
        if request["authority_approval_file"] is not None
        else None
    )
    try:
        public_snapshot = inspect_public_kernel(
            root,
            authority_approval_file=authority_path,
            inventory_mode=_staged_inventory_mode(root),
            include_engine_manifest=include_manifest,
        )
    except AdapterError as error:
        if error.code in INDETERMINATE_ADAPTER_ERRORS:
            diagnosis = {
                "contract_version": "workbench-kit-diagnosis/v1",
                "classification": "indeterminate",
                "embedded_engine": {
                    "state": "indeterminate",
                    "equivalence_receipt_digest": None,
                },
                "provenance": {
                    "kind": None,
                    "state": "absent",
                    "receipt_digest": None,
                    "ref": None,
                },
                "language": None,
                "blockers": [{
                    "code": "kernel-readiness-indeterminate",
                    "ref": error.ref,
                }],
            }
            require_workspace_binding(root_fd, root)
            return diagnosis
        raise CliError(error.code, error.ref) from error
    plan = plan_from_snapshot(
        root,
        request=request,
        bundle=bundle,
        public_snapshot=public_snapshot,
        receipt_inputs=receipt_inputs,
    )
    require_workspace_binding(root_fd, root)
    return plan


def dry_run_upgrade(
    request: dict[str, Any], bundle: dict[str, Any]
) -> dict[str, Any]:
    if request["mode"] != "dry-run":
        raise CliError("mode-invalid", request["mode"])
    root = _resolve_workspace(request["workspace"])
    try:
        with workspace_lock(root) as root_fd:
            return _dry_run_upgrade_locked(
                request, bundle, root, root_fd
            )
    except JournalError as error:
        raise CliError(error.code, error.ref) from error


def load_runtime_bundle(plugin_root: pathlib.Path) -> dict[str, Any]:
    try:
        root = pathlib.Path(plugin_root).resolve(strict=True)
        runtime = strict_load(
            (root / "receipts/upgrade-runtime.json").read_bytes(),
            "receipts/upgrade-runtime.json",
        )
        runtime_fields = {
            "contract_version",
            "planner_revision",
            "generator_source_revision",
            "legacy_engine_markers",
            "plugin_equivalence_file",
        }
        if (
            not isinstance(runtime, dict)
            or set(runtime) != runtime_fields
            or runtime["contract_version"]
            != "workbench-kit-upgrade-runtime/v1"
        ):
            raise CliError("runtime-bundle-invalid", "upgrade-runtime.json")
        planner_revision = runtime["planner_revision"]
        if (
            not isinstance(planner_revision, str)
            or len(planner_revision) not in (40, 64)
            or any(
                character not in "0123456789abcdef"
                for character in planner_revision
            )
        ):
            raise CliError(
                "runtime-bundle-invalid", "planner_revision"
            )
        plugin = strict_load(
            (root / ".claude-plugin/plugin.json").read_bytes(),
            ".claude-plugin/plugin.json",
        )
        version = plugin["version"]
        core = (root / "scaffold/AGENTS.core.md").read_bytes()
        generator = {
            "contract_version": "workbench-kit-generator-receipt/v1",
            "receipt_id": "generator-" + version,
            "generator_id": "workbench-kit:generate-workbench",
            "generator_version": version,
            "source_revision": runtime["generator_source_revision"],
            "compose_contract": "workbench-kit-compose/v1",
            "header_base64": base64.b64encode(COMPOSE_HEADER).decode("ascii"),
            "core_base64": base64.b64encode(core).decode("ascii"),
            "core_digest": canonical_digest(core, raw=True),
            "separator_base64": base64.b64encode(COMPOSE_SEPARATOR).decode(
                "ascii"
            ),
            "settings_owned": {
                "marketplace": {
                    "source": {
                        "source": "github",
                        "repo": "YOOGOMJA/workbench-kit",
                    }
                },
                "plugin_enabled": True,
            },
            "generated_nodes": [
                {
                    "path": ".claude/settings.json",
                    "node_type": "file",
                    "mode": "100644",
                },
                {
                    "path": "AGENTS.md",
                    "node_type": "file",
                    "mode": "100644",
                },
                {
                    "path": "CLAUDE.md",
                    "node_type": "file",
                    "mode": "100644",
                },
            ],
            "receipt_digest": None,
        }
        generator["receipt_digest"] = canonical_digest(
            generator, null_field="receipt_digest"
        )
        generator = validate_generator_receipt(generator)
        marker_values = runtime["legacy_engine_markers"]
        if not isinstance(marker_values, list):
            raise CliError(
                "runtime-bundle-invalid", "legacy_engine_markers"
            )
        markers = [validate_relative_path(item) for item in marker_values]
        if (
            not markers
            or markers != sorted(markers)
            or len(markers) != len(set(markers))
        ):
            raise CliError(
                "runtime-bundle-invalid", "legacy_engine_markers"
            )
        equivalence_input = None
        equivalence_file = runtime["plugin_equivalence_file"]
        if equivalence_file is not None:
            if (
                not isinstance(equivalence_file, str)
                or pathlib.PurePosixPath(equivalence_file).is_absolute()
                or ".." in pathlib.PurePosixPath(equivalence_file).parts
            ):
                raise CliError(
                    "runtime-bundle-invalid", "plugin_equivalence_file"
                )
            raw_equivalence = (root / equivalence_file).read_bytes()
            equivalence = validate_equivalence_receipt(
                strict_load(raw_equivalence, equivalence_file)
            )
            if raw_equivalence != canonical_bytes(equivalence):
                raise CliError(
                    "runtime-bundle-invalid", "plugin_equivalence_file"
                )
            equivalence_input = {
                "receipt": equivalence,
                "object_digest": canonical_digest(equivalence),
                "source_digest": canonical_digest(raw_equivalence, raw=True),
            }
        return {
            "planner": {
                "contract_version": "workbench-kit-planner/v1",
                "plugin_version": version,
                "planner_revision": runtime["planner_revision"],
            },
            "generator_receipts": [generator],
            "target_generator_receipt": generator,
            "plugin_equivalence_input": equivalence_input,
            "legacy_engine_markers": markers,
        }
    except CliError:
        raise
    except (ContractError, KeyError, OSError, TypeError) as error:
        raise CliError(
            "runtime-bundle-invalid", str(plugin_root)
        ) from error


def _load_plan(
    request: dict[str, Any], root: pathlib.Path
) -> tuple[dict[str, Any], str]:
    raw = _read_external_file(pathlib.Path(request["plan_file"]), root)
    try:
        plan = validate_plan(strict_load(raw, request["plan_file"]))
    except ContractError as error:
        raise CliError("plan-file-invalid", request["plan_file"]) from error
    if raw != canonical_bytes(plan):
        raise CliError("plan-file-invalid", request["plan_file"])
    try:
        plan_root = _resolve_workspace(plan["workspace"]["root"])
    except CliError as error:
        raise CliError(
            "workspace-mismatch", plan["workspace"]["root"]
        ) from error
    if plan_root != root:
        raise CliError("workspace-mismatch", plan["workspace"]["root"])
    return plan, canonical_digest(raw, raw=True)


def _plan_route(plan: dict[str, Any]) -> str:
    task_contract = plan["workspace"]["migration_task"]["task_contract"]
    if task_contract == "workbench-task/v2":
        return "current-v2"
    if plan["classification_before"] == "migration-staged":
        return "staged-v2"
    return "implicit-v1"


def _apply_inputs(
    request: dict[str, Any], root: pathlib.Path, plan: dict[str, Any]
) -> dict[str, dict[str, Any] | None]:
    route = _plan_route(plan)
    validate_route_flags(request, route)
    inputs = {
        "authority": _optional_projection(
            request,
            root,
            "authority_approval_file",
            "bootstrap-authority",
        ),
        "reviewed_overlay": _optional_projection(
            request,
            root,
            "reviewed_overlay_file",
            "reviewed-overlay",
        ),
        "removal_approval": _optional_projection(
            request,
            root,
            "removal_approval_file",
            "removal-approval",
        ),
    }
    expected = {
        "authority": plan["inputs"]["bootstrap_authority_approval"],
        "reviewed_overlay": plan["inputs"]["reviewed_overlay"],
        "removal_approval": plan["removal_approval"],
    }
    for field in expected:
        if inputs[field] != expected[field]:
            raise CliError("plan-input-stale", field)
    if route == "implicit-v1" and language_decision(
        request["language"], route
    ) != plan["inputs"]["language"]:
        raise CliError("plan-input-stale", "language")
    return inputs


def _validation(
    *,
    status: str,
    classification: str | None,
    basis_kind: str | None,
    basis_digest: str | None,
    blockers: list[dict[str, str]],
) -> dict[str, Any]:
    validation = {
        "status": status,
        "classification_after": classification,
        "basis_kind": basis_kind,
        "basis_digest": basis_digest,
        "blockers": sorted(blockers, key=lambda item: (item["code"], item["ref"])),
        "digest": None,
    }
    validation["digest"] = canonical_digest(validation, null_field="digest")
    return validation


def _candidate_validator(
    request: dict[str, Any], bundle: dict[str, Any]
):
    def validate_candidate(plan: dict[str, Any]) -> dict[str, Any]:
        root = pathlib.Path(plan["workspace"]["root"])
        authority_path = (
            pathlib.Path(request["authority_approval_file"])
            if request["authority_approval_file"] is not None
            else None
        )
        try:
            snapshot = inspect_public_kernel(
                root,
                authority_approval_file=authority_path,
                inventory_mode=(
                    "bootstrap-show"
                    if plan["legacy_inventory"]["command"] == "bootstrap-show"
                    else "show"
                ),
                include_engine_manifest=plan["engine_manifest"] is not None,
            )
            equivalence_input = bundle.get("plugin_equivalence_input")
            diagnosis = diagnose_workspace(
                root,
                snapshot,
                generator_receipts=bundle["generator_receipts"],
                equivalence_receipt=(
                    equivalence_input["receipt"]
                    if equivalence_input is not None
                    else None
                ),
                legacy_engine_markers=bundle.get(
                    "legacy_engine_markers", ()
                ),
            )
            blockers = list(diagnosis["blockers"])
            if diagnosis["classification"] != plan["target_classification"]:
                blockers.append({
                    "code": "candidate-classification-mismatch",
                    "ref": diagnosis["classification"],
                })
            if diagnosis["embedded_engine"]["state"] != plan["embedded_engine"]["after"]:
                blockers.append({
                    "code": "candidate-embedded-mismatch",
                    "ref": diagnosis["embedded_engine"]["state"],
                })
            if plan["target_classification"] == "migration-staged":
                receipt_node = _inspect_node(root, ".workbench/migration.json")
                receipt = validate_migration_receipt(
                    strict_load(
                        receipt_node["content"], ".workbench/migration.json"
                    )
                )
                basis_kind = "migration-candidate"
                basis_digest = receipt["candidate_basis_digest"]
            else:
                basis_kind = "removal-plan"
                basis_digest = plan["removal_plan_basis_digest"]
            if blockers:
                return _validation(
                    status="failed",
                    classification=diagnosis["classification"],
                    basis_kind=basis_kind,
                    basis_digest=basis_digest,
                    blockers=blockers,
                )
            return _validation(
                status="passed",
                classification=diagnosis["classification"],
                basis_kind=basis_kind,
                basis_digest=basis_digest,
                blockers=[],
            )
        except (AdapterError, ContractError, OSError) as error:
            return _validation(
                status="failed",
                classification=None,
                basis_kind=None,
                basis_digest=None,
                blockers=[{
                    "code": "candidate-validation-failed",
                    "ref": getattr(error, "ref", str(root)),
                }],
            )

    return validate_candidate


def _utc_now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )


def _apply_upgrade_locked(
    request: dict[str, Any],
    bundle: dict[str, Any],
    root: pathlib.Path,
    root_fd: int,
) -> dict[str, Any]:
    require_workspace_binding(root_fd, root)
    plan, plan_source_digest = _load_plan(request, root)
    _apply_inputs(request, root, plan)
    if plan["blockers"] or not plan["actionable"]:
        raise CliError("plan-not-actionable", plan["plan_digest"])
    try:
        location = resolve_journal_location_locked(
            root,
            root_fd,
            plan["plan_digest"],
            journal_dir=(
                pathlib.Path(request["journal_dir"])
                if request["journal_dir"] is not None
                else None
            ),
        )
        try:
            os.lstat(location["journal"])
            journal_exists = True
        except FileNotFoundError:
            journal_exists = False
        if not journal_exists:
            dry_request = dict(request)
            dry_request.update({
                "mode": "dry-run",
                "plan_file": None,
                "journal_dir": None,
                "remove_embedded_engine": (
                    plan["removal_plan_basis_digest"] is not None
                ),
            })
            regenerated = _dry_run_upgrade_locked(
                dry_request, bundle, root, root_fd
            )
            if canonical_bytes(regenerated) != canonical_bytes(plan):
                raise CliError("plan-stale", plan["plan_digest"])
            journal = build_prepared_journal(
                plan, plan_source_digest, _utc_now()
            )
            install_prepared_journal_locked(
                journal, location, plan, root_fd
            )
        return execute_upgrade_locked(
            plan,
            location,
            root_fd,
            plan_source_digest=plan_source_digest,
            updated_at=_utc_now(),
            validate_after=_candidate_validator(request, bundle),
        )
    except JournalError as error:
        raise CliError(error.code, error.ref) from error


def apply_upgrade(
    request: dict[str, Any], bundle: dict[str, Any]
) -> dict[str, Any]:
    if request["mode"] != "apply":
        raise CliError("mode-invalid", request["mode"])
    root = _resolve_workspace(request["workspace"])
    try:
        with workspace_lock(root) as root_fd:
            return _apply_upgrade_locked(
                request, bundle, root, root_fd
            )
    except JournalError as error:
        raise CliError(error.code, error.ref) from error
