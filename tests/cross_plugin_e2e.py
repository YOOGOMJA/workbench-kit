def assert_toolbox_free_v1(workspace: pathlib.Path) -> None:
    contract, _ = run_json(
        (WORKBENCH, "contract", "show", "--format", "json"), cwd=workspace
    )
    if contract["workspace"]["schema"] != "workbench/v1":
        fail("generated-minimal caller did not retain implicit v1 behavior")
    doctor, status = run_json(
        (WORKBENCH, "doctor", "--format", "json"),
        cwd=workspace,
        expected=(0, 1),
    )
    if status != 1 or doctor["ready"] is not False:
        fail("implicit v1 doctor must remain a read-only not-ready diagnosis")
    if (workspace / "products").exists() or (workspace / ".toolbox").exists():
        fail("toolbox state appeared in a toolbox-free v1 caller")


