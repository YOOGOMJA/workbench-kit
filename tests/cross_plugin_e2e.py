def fail(message: str) -> None:
    raise AssertionError(message)


def run(arguments, *, cwd=None, env=None, expected=(0,)):
    process = subprocess.run(
        [str(item) for item in arguments],
        cwd=None if cwd is None else str(cwd),
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if process.returncode not in expected:
        fail(
            "command failed ({status}): {command}\nstdout:\n{stdout}\nstderr:\n{stderr}".format(
                status=process.returncode,
                command=" ".join(str(item) for item in arguments),
                stdout=process.stdout,
                stderr=process.stderr,
            )
        )
    return process


def run_json(arguments, *, cwd=None, env=None, expected=(0,)):
    process = run(arguments, cwd=cwd, env=env, expected=expected)
    try:
        return json.loads(process.stdout), process.returncode
    except json.JSONDecodeError as error:
        fail("public command did not emit JSON: {}\n{}".format(error, process.stdout))


def git(repository, *arguments):
    return run(("git", "-C", repository, *arguments))


def write_json(path: pathlib.Path, value, mode=0o600) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    path.chmod(mode)


def sha256(raw: bytes) -> str:
    return "sha256:" + hashlib.sha256(raw).hexdigest()


def canonical_digest(value) -> str:
    raw = (
        json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n"
    ).encode("utf-8")
    return sha256(raw)


def initialize_repository(path: pathlib.Path, origin: pathlib.Path) -> str:
    run(("git", "init", "-q", "--bare", origin))
    run(("git", "init", "-q", "-b", "main", path))
    git(path, "config", "user.name", "Integration Fixture")
    git(path, "config", "user.email", "fixture@example.invalid")
    git(path, "add", "-A")
    git(path, "commit", "-qm", "fixture: initialize caller workspace")
    git(path, "remote", "add", "origin", origin)
    git(path, "push", "-q", "-u", "origin", "main")
    git(origin, "symbolic-ref", "HEAD", "refs/heads/main")
    return git(path, "rev-parse", "HEAD").stdout.strip()


def safe_extract_legacy_archive(destination: pathlib.Path) -> None:
    encoded = b"".join(LEGACY_ARCHIVE.read_bytes().split())
    compressed = base64.b64decode(encoded, validate=True)
    with tarfile.open(fileobj=io.BytesIO(compressed), mode="r:gz") as archive:
        for member in archive.getmembers():
            pure = pathlib.PurePosixPath(member.name)
            if pure.is_absolute() or ".." in pure.parts:
                fail("unsafe legacy archive member: {}".format(member.name))
            if member.issym():
                target = pathlib.PurePosixPath(member.linkname)
                if target.is_absolute():
                    fail("unsafe legacy archive symlink: {}".format(member.name))
        archive.extractall(str(destination))


def materialize_generated_files(workspace: pathlib.Path) -> None:
    overlay = (workspace / "AGENTS.overlay.md").read_text(encoding="utf-8")
    core = (
        ROOT / "plugins/workbench-kit/scaffold/AGENTS.core.md"
    ).read_text(encoding="utf-8")
    composed = COMPOSE_HEADER + core + COMPOSE_SEPARATOR + overlay
    (workspace / "AGENTS.md").write_text(composed, encoding="utf-8")
    (workspace / "CLAUDE.md").write_text(composed, encoding="utf-8")
    settings = {
        "permissions": {"allow": ["Read"]},
        "extraKnownMarketplaces": {
            "workbench-kit": {
                "source": {
                    "source": "github",
                    "repo": "YOOGOMJA/workbench-kit",
                }
            }
        },
        "enabledPlugins": {
            "workbench@workbench-kit": True,
            "user-plugin@example": True,
        },
    }
    settings_path = workspace / ".claude/settings.json"
    settings_path.parent.mkdir(parents=True, exist_ok=True)
    write_json(settings_path, settings, mode=0o644)


